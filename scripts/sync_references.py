"""Build self-contained Skill references from docs; --check never writes files."""

import argparse
import hashlib
import json
import re
from pathlib import Path
from urllib.parse import unquote, urlsplit


ROOT = Path(__file__).resolve().parents[1]
PACKAGES = {
    "techjudge": Path("plugin/techjudge/skills/tech-judgment/references"),
    "harness": Path("plugin/harness/skills/harness-engineering/references"),
}


def read(root, relative):
    # read_text's universal-newline mode converts CRLF and CR to LF.
    return (root / relative).read_text(encoding="utf-8")


def validate_links(root, outputs):
    """Check prospective references and entry points before writing any output."""
    for directory in PACKAGES.values():
        plugin = (root / directory).parents[2].resolve()
        documents = { (root / path).resolve(): body for path, body in outputs.items()
                     if path.suffix == ".md" and directory in path.parents }
        for entry in plugin.glob("skills/*/SKILL.md"):
            documents[entry.resolve()] = entry.read_text(encoding="utf-8")
        for path, body in documents.items():
            for link in re.findall(r"\]\(([^)\s]+)\)", body):
                parts = urlsplit(link)
                if parts.scheme or parts.netloc or not parts.path:
                    continue
                target = (path.parent / unquote(parts.path)).resolve()
                if plugin not in target.parents:
                    raise ValueError("{}: link leaves plugin: {}".format(path.name, link))
                if target not in documents:
                    raise ValueError("{}: missing packaged reference: {}".format(path.name, link))


def build(root):
    outputs = {}
    sources = {name: {} for name in PACKAGES}

    def add(package, target, source, content=None):
        original = read(root, source)
        sources[package][target] = {
            "source": source.as_posix(),
            "sha256": hashlib.sha256(original.encode("utf-8")).hexdigest(),
        }
        header = "<!-- Generated by scripts/sync_references.py; edit {}. -->\n\n".format(source.as_posix())
        outputs[PACKAGES[package] / target] = header + (original if content is None else content)

    index_source = Path("docs/stacks/README.md")
    index = read(root, index_source)
    match = re.search(r"^## 목록\n(.*?)(?=^## |\Z)", index, re.M | re.S)
    if not match:
        raise ValueError("docs/stacks/README.md: missing '목록' section")
    table = match.group(1).strip()
    listed = set(re.findall(r"\]\(([\w-]+/[\w-]+\.md)\)", table))
    cards = sorted((root / "docs/stacks").glob("*/*.md"))
    actual = {p.relative_to(root / "docs/stacks").as_posix() for p in cards}
    if not actual or listed != actual:
        raise ValueError("Stack index must list every card exactly by path; missing={}, extra={}".format(
            sorted(actual - listed), sorted(listed - actual)))
    table = re.sub(r"\]\(([\w-]+/[\w-]+\.md)\)", r"](stacks/\1)", table)
    intro = ("# 문제별 기술 참조\n\n"
             "현재 결정과 연결되는 카드를 골라 읽는다. 표의 기술은 대안·보완 요소·진단 도구가 섞여 있으므로 역할을 구분한다.\n"
             "기준선은 비교의 출발점이며, 작은 규모에서도 학습은 독립적인 도입 이유다.\n"
             "카드의 출처와 확인 범위를 읽고 구현에 영향을 주는 버전별 동작을 재확인한다.\n\n")
    add("techjudge", "index.md", index_source, intro + table + "\n")
    for card in cards:
        relative = card.relative_to(root)
        target = "stacks/" + card.relative_to(root / "docs/stacks").as_posix()
        add("techjudge", target, relative)
    # Two cards link ../../harness-engineering.md. Include it in each independent package.
    for package in PACKAGES:
        add(package, "harness-engineering.md", Path("docs/harness-engineering.md"))
    for name, entries in sources.items():
        metadata = {"schema_version": 1, "hash_encoding": "UTF-8 with LF line endings", "files": entries}
        outputs[PACKAGES[name] / "sources.json"] = json.dumps(metadata, ensure_ascii=False, indent=2) + "\n"
    validate_links(root, outputs)
    return outputs


def differences(root, outputs):
    changes = []
    for relative, expected in sorted(outputs.items()):
        path = root / relative
        if not path.is_file():
            changes.append(("missing", relative))
        elif read(root, relative) != expected:
            changes.append(("changed", relative))
    for directory in PACKAGES.values():
        for path in sorted((root / directory).rglob("*")):
            if path.is_file() and path.relative_to(root) not in outputs:
                changes.append(("unexpected", path.relative_to(root)))
    return changes


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args(argv)
    try:
        outputs = build(ROOT)
        changes = differences(ROOT, outputs)
        if args.check or any(kind == "unexpected" for kind, _ in changes):
            for kind, path in changes:
                print("{}: {}".format(kind, path.as_posix()))
            if changes:
                if not args.check:
                    print("Remove or relocate unexpected generated files after reviewing them; no files were written.")
                return 1
        else:
            for _, relative in changes:
                path = ROOT / relative
                path.parent.mkdir(parents=True, exist_ok=True)
                with path.open("w", encoding="utf-8", newline="\n") as stream:
                    stream.write(outputs[relative])
        print("References {}: {} files".format("verified" if args.check else "synchronized", len(outputs)))
        return 0
    except (OSError, ValueError) as error:
        print("Reference generation failed: {}".format(error))
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
